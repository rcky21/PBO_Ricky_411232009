    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
        int totalHarga = Integer.parseInt(jTextField5.getText());
        int jumlahBayar = Integer.parseInt(jTextField6.getText());
        
        if (jumlahBayar < totalHarga) {
            javax.swing.JOptionPane.showMessageDialog(this, "Uang pembayaran kurang!");
        } else {
            int sisa = jumlahBayar - totalHarga;

            jLabel10.setText(String.valueOf(sisa));
        }
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pastikan input angka benar!");
    }
    
    }//GEN-LAST:event_jButton1ActionPerformed

