    private void jTextField4FocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_jTextField4FocusLost
        // TODO add your handling code here:
        if (!jTextField4.getText().isEmpty() && !jTextField2.getText().isEmpty()) {
        try {
            // Ambil data
            int hargasewa = Integer.parseInt(jTextField2.getText());
            int lamasewa = Integer.parseInt(jTextField4.getText());
            
            // Hitung total
            int total = lamasewa * hargasewa;
            
            // Tampilkan hasil di jTextField5
            jTextField5.setText(String.valueOf(total));
            
        } catch (NumberFormatException e) {
            // Jika input bukan angka
            javax.swing.JOptionPane.showMessageDialog(this, "Masukkan angka yang valid untuk Lama Sewa!");
        }
    }
    }//GEN-LAST:event_jTextField4FocusLost

